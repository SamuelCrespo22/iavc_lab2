"""Train/validation/test protocol built on top of the supplied splits.

The supplied ``<category>_val.txt`` files are the held-out test set described in
the assignment. This module carves a validation set out of the supplied
``<category>_train.txt`` files and writes three lists per category:

    <out-dir>/<category>_train.txt   training images (supplied train minus validation)
    <out-dir>/<category>_val.txt     validation images (for model selection)
    <out-dir>/<category>_test.txt    copy of the supplied <category>_val.txt

The split is made per image, not per category file, because some images belong
to several categories (e.g. horse + person). An image therefore lands in the
same subset for every category it belongs to. Images are stratified by their
rarest category so that small classes keep the requested validation fraction.

The output directory must differ from ``data/splits``: ``loadSamplesTable``
globs every ``*.txt`` file there and would pick up the new lists.
"""

from collections import defaultdict
from pathlib import Path

import numpy as np


def readSplitFiles(split_dir, subset):
    """Return ``{category: [image ids]}`` for ``<category>_<subset>.txt`` files."""
    lists = {}
    for path in sorted(Path(split_dir).glob(f"*_{subset}.txt")):
        category = path.name.split("_")[0]
        with open(path, "r") as f:
            lists[category] = [l.strip() for l in f if l.strip()]
    return lists


def makeValidationSplit(train_lists, val_fraction=0.2, seed=42):
    """Assign each training image to 'train' or 'val', stratified by rarest category.

    Args:
        train_lists (dict): ``{category: [image ids]}`` from the supplied train files.
        val_fraction (float): Fraction of images per stratum moved to validation.
        seed (int): Random seed for reproducibility.

    Returns:
        dict: ``{image id: "train" | "val"}``.
    """
    image_categories = defaultdict(set)
    for category, ids in train_lists.items():
        for image_id in ids:
            image_categories[image_id].add(category)

    # Stratum = the image's rarest category, so rare classes are split evenly.
    counts = {c: len(ids) for c, ids in train_lists.items()}
    strata = defaultdict(list)
    for image_id, cats in image_categories.items():
        rarest = min(cats, key=lambda c: (counts[c], c))
        strata[rarest].append(image_id)

    rng = np.random.default_rng(seed)
    assignment = {}
    for category in sorted(strata):
        ids = sorted(strata[category])
        perm = rng.permutation(len(ids))
        num_val = int(round(val_fraction * len(ids)))
        for rank, idx in enumerate(perm):
            assignment[ids[idx]] = "val" if rank < num_val else "train"
    return assignment


def writeProtocolSplits(split_dir="data/splits", out_dir="data/splits_protocol",
                        val_fraction=0.2, seed=42):
    split_dir, out_dir = Path(split_dir), Path(out_dir)
    assert split_dir.resolve() != out_dir.resolve(), "out_dir must differ from split_dir"
    out_dir.mkdir(parents=True, exist_ok=True)

    train_lists = readSplitFiles(split_dir, "train")
    test_lists = readSplitFiles(split_dir, "val")
    assignment = makeValidationSplit(train_lists, val_fraction, seed)

    summary = []
    for category, ids in train_lists.items():
        subsets = {
            "train": [i for i in ids if assignment[i] == "train"],
            "val": [i for i in ids if assignment[i] == "val"],
            "test": test_lists.get(category, []),
        }
        for subset, subset_ids in subsets.items():
            with open(out_dir / f"{category}_{subset}.txt", "w") as f:
                f.write("\n".join(subset_ids) + "\n")
        summary.append((category, *(len(subsets[s]) for s in ("train", "val", "test"))))

    with open(out_dir / "README.txt", "w") as f:
        f.write(f"Generated by src/splits.py from {split_dir} "
                f"(val_fraction={val_fraction}, seed={seed}).\n"
                "test = supplied *_val.txt files; train/val = supplied *_train.txt split per image.\n")

    print(f"{'category':12s} {'train':>6s} {'val':>6s} {'test':>6s}")
    for row in summary:
        print(f"{row[0]:12s} {row[1]:6d} {row[2]:6d} {row[3]:6d}")
    print(f"Wrote protocol splits to {out_dir}")


def loadProtocolSubset(category, encoding, subset="train", root_dir="data",
                       protocol_dir="data/splits_protocol"):
    """Load positive (category) and negative (background) encodings for a protocol subset.

    'train' and 'val' rows come from the supplied ``*_train.npz`` encodings and
    'test' rows from the supplied ``*_val.npz`` encodings, filtered by the
    image lists written by ``writeProtocolSplits``.

    Returns:
        hist, labels (+1 / -1), names, in the same format as ``loadEncodingSubset``.
    """
    assert subset in ["train", "val", "test"], "subset must be 'train', 'val' or 'test'"
    source = "val" if subset == "test" else "train"

    hists, labels, names = [], [], []
    for cat, label in [(category, 1), ("background", -1)]:
        with open(Path(protocol_dir) / f"{cat}_{subset}.txt", "r") as f:
            keep = {l.strip() for l in f if l.strip()}
        data = np.load(f"{root_dir}/encodings/{encoding}/{cat}_{source}.npz")
        mask = np.isin(data["file_names"], list(keep))
        assert mask.sum() == len(keep), f"{cat}_{subset}: {len(keep) - mask.sum()} images missing in encodings"
        hists.append(data["histograms"][mask])
        names.append(data["file_names"][mask])
        labels.append(np.full(mask.sum(), label, dtype=np.int32))

    return np.concatenate(hists), np.concatenate(labels), np.concatenate(names)


